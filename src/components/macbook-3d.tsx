"use client";

import { useEffect, useRef, useState } from "react";
import { Box3, DirectionalLight, Group, HemisphereLight, Mesh, PerspectiveCamera, Scene, SRGBColorSpace, Texture, Vector3, WebGLRenderer, ACESFilmicToneMapping } from "three";
import { OrbitControls } from "three/addons/controls/OrbitControls.js";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { Minus, Plus, RotateCcw } from "lucide-react";

type Angle = "perspectiva" | "frente" | "lateral" | "superior";
const views: { id: Angle; label: string; position: [number, number, number] }[] = [
  { id: "perspectiva", label: "Perspectiva", position: [1.6, 1.1, 2.2] },
  { id: "frente", label: "Frente", position: [0, 0.6, 2.8] },
  { id: "lateral", label: "Lateral", position: [2.8, 0.6, 0.2] },
  { id: "superior", label: "Superior", position: [0.1, 2.8, 0.5] },
];
type Viewer = { camera: PerspectiveCamera; controls: OrbitControls; radius: number };

/** Displays third-party GLB files; no 3D geometry is generated by volta. */
export function Macbook3D({ series, screen }: { color: string; series: "Air" | "Pro"; screen: string }) {
  const mount = useRef<HTMLDivElement>(null);
  const viewer = useRef<Viewer | null>(null);
  const [angle, setAngle] = useState<Angle>("perspectiva");
  const [error, setError] = useState(false);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const host = mount.current;
    if (!host) return;
    let cancelled = false;
    let renderer: WebGLRenderer;
    try { renderer = new WebGLRenderer({ antialias: true, alpha: true, powerPreference: "low-power" }); }
    catch { const timer = window.setTimeout(() => { setError(true); setLoading(false); }, 0); return () => clearTimeout(timer); }
    renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
    renderer.outputColorSpace = SRGBColorSpace;
    renderer.toneMapping = ACESFilmicToneMapping;
    renderer.setClearColor(0xffffff, 0);
    renderer.domElement.setAttribute("aria-hidden", "true");
    renderer.domElement.style.width = "100%";
    renderer.domElement.style.height = "100%";
    host.appendChild(renderer.domElement);
    const scene = new Scene();
    scene.add(new HemisphereLight(0xffffff, 0x778296, 2.4));
    const key = new DirectionalLight(0xffffff, 3.6); key.position.set(4, 8, 6); scene.add(key);
    const fill = new DirectionalLight(0xdceaff, 2); fill.position.set(-5, 3, -4); scene.add(fill);
    const camera = new PerspectiveCamera(38, 1, 0.01, 3000);
    const controls = new OrbitControls(camera, renderer.domElement);
    controls.enableDamping = true;
    controls.enablePan = false;
    controls.minPolarAngle = 0.1;
    controls.maxPolarAngle = Math.PI * 0.9;
    const state: Viewer = { camera, controls, radius: 4 };
    viewer.current = state;
    const url = screen.trim().startsWith("16") ? "/models/macbook-16.glb" : "/models/macbook-14.glb";
    new GLTFLoader().load(url, (gltf) => {
      if (cancelled) return;
      const model: Group = gltf.scene;
      const bounds = new Box3().setFromObject(model);
      const center = bounds.getCenter(new Vector3());
      const diameter = bounds.getSize(new Vector3()).length();
      if (!Number.isFinite(diameter) || diameter === 0) { setError(true); setLoading(false); return; }
      model.position.sub(center);
      scene.add(model);
      state.radius = diameter * 1.2;
      controls.minDistance = diameter * 0.55;
      controls.maxDistance = diameter * 2.8;
      camera.near = Math.max(0.001, diameter / 1000);
      camera.far = diameter * 30;
      camera.position.copy(new Vector3(...views[0].position).normalize().multiplyScalar(state.radius));
      camera.updateProjectionMatrix();
      controls.update();
      setLoading(false);
    }, undefined, () => { if (!cancelled) { setError(true); setLoading(false); } });
    const resize = () => {
      const width = host.clientWidth, height = host.clientHeight;
      if (!width || !height) return;
      camera.aspect = width / height;
      camera.updateProjectionMatrix();
      renderer.setSize(width, height, false);
    };
    const observer = new ResizeObserver(resize);
    observer.observe(host); resize();
    let frame = 0;
    let visible = true;
    const draw = () => {
      frame = 0;
      if (!visible || document.hidden) return;
      controls.update();
      renderer.render(scene, camera);
      frame = requestAnimationFrame(draw);
    };
    const start = () => { if (!frame && visible && !document.hidden) frame = requestAnimationFrame(draw); };
    const intersection = new IntersectionObserver(([entry]) => {
      visible = entry?.isIntersecting ?? false;
      if (visible) start(); else { cancelAnimationFrame(frame); frame = 0; }
    });
    intersection.observe(host);
    document.addEventListener("visibilitychange", start);
    start();
    return () => {
      cancelled = true;
      cancelAnimationFrame(frame);
      intersection.disconnect(); observer.disconnect();
      document.removeEventListener("visibilitychange", start);
      controls.dispose(); viewer.current = null;
      scene.traverse((node) => {
        if (!(node instanceof Mesh)) return;
        node.geometry.dispose();
        const materials = Array.isArray(node.material) ? node.material : [node.material];
        materials.forEach((material) => {
          for (const value of Object.values(material)) {
            if (value instanceof Texture) value.dispose();
          }
          material.dispose();
        });
      });
      renderer.dispose();
      if (host.contains(renderer.domElement)) host.removeChild(renderer.domElement);
    };
  }, [screen]);

  const select = (view: typeof views[number]) => {
    setAngle(view.id);
    const state = viewer.current;
    if (!state) return;
    state.camera.position.copy(new Vector3(...view.position).normalize().multiplyScalar(state.radius));
    state.controls.update();
  };
  const zoom = (direction: number) => {
    const state = viewer.current;
    if (!state) return;
    const offset = state.camera.position.clone().sub(state.controls.target);
    offset.multiplyScalar(direction).clampLength(state.controls.minDistance, state.controls.maxDistance);
    state.camera.position.copy(state.controls.target.clone().add(offset));
    state.controls.update();
  };

  return <div className="sf-3d-viewer">
    <div className="sf-3d-stage" role="group" aria-label={`Visualização 3D ilustrativa de MacBook. Modelo pronto de referência para a linha ${series}.`}>
      <div className="sf-3d-canvas" ref={mount} />
      {loading && !error && <div className="sf-3d-error" role="status">Carregando modelo 3D…</div>}
      {error && <div className="sf-3d-error" role="status">Não foi possível carregar o 3D. As fotografias da unidade estão disponíveis na outra aba.</div>}
      <div className="sf-3d-stage-meta"><span>MODELO 3D DE REFERÊNCIA</span><span>Arraste para girar</span></div>
    </div>
    <div className="sf-3d-controls" role="group" aria-label="Controles do modelo">
      {views.map((view) => <button key={view.id} type="button" className={angle === view.id ? "active" : ""} aria-pressed={angle === view.id} disabled={loading || error} onClick={() => select(view)}>{view.label}</button>)}
      <button type="button" className="sf-3d-reset" aria-label="Aproximar" disabled={loading || error} onClick={() => zoom(0.85)}><Plus size={16} /></button>
      <button type="button" className="sf-3d-reset" aria-label="Afastar" disabled={loading || error} onClick={() => zoom(1.15)}><Minus size={16} /></button>
      <button type="button" className="sf-3d-reset" aria-label="Restaurar câmera" disabled={loading || error} onClick={() => select(views[0])}><RotateCcw size={16} /></button>
    </div>
    <p className="sf-3d-disclaimer">Modelo 3D pronto do projeto Wistant (licença MIT). Referência visual de MacBook Pro, com possíveis diferenças de formato, conexões, acabamento e cor em relação ao aparelho anunciado. Confira a conservação nas fotos reais.</p>
  </div>;
}
